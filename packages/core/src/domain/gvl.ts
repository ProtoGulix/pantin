import type { IoMappedChannel, IoMappingResponse } from "@pantin/protocol";
import { isDottedVariable } from "./io-identifiers.ts";
import { presentationOf, rulesOf } from "./io-transports.ts";

// The CODESYS global variable list of a valid mapping (ADR 0045 point 9, ADR
// 0049 points 9 and 11, ADR 0064 point 9): modules in the order of io.json and
// channels in canonical order. No AT addresses: CODESYS assigns %I/%Q addresses
// in the device tree, where the channels are mapped to these variables. One
// generator serves `pantin gvl` and the GET .../io/gvl route.
//
// A dotted variable (`GVL_IO.Verin1.FinCourseSortie`) names something the PLC
// program declares already: it is left out of the declarations and listed in
// the header comment, so that the programmer sees what Pantin expects to exist.

type MappingModule = IoMappingResponse["modules"][number];

const HEADER = [
  '// Generated by "pantin gvl" from io.json: do not edit it,',
  "// change the mapping and generate it again.",
  "//",
  "// WARNING (ADR 0046 point 10): a PLC trusts Pantin's feedback. The PLC under",
  "// test must never drive live outputs at the same time: use a SoftPLC, or a",
  "// controller with its field I/O disconnected.",
];

// The OPC UA modules read their variables in a GVL the user names when pasting this text
// (ADR 0065 point 3): the header says which name each module expects.
function scopeNote(modules: IoMappingResponse["modules"]): string[] {
  const keysByScope = new Map<string, string[]>();
  for (const module of modules) {
    const scope = rulesOf(module.transport).variableScope(module.transport);
    if (scope !== null) {
      keysByScope.set(scope, [...(keysByScope.get(scope) ?? []), module.key]);
    }
  }
  if (keysByScope.size === 0) {
    return [];
  }
  return [
    "//",
    ...[...keysByScope].map(
      ([scope, keys]) =>
        `// Paste this list into a GVL named ${scope} (module ${keys.join(", ")}).`,
    ),
    "//",
    "// WARNING (ADR 0065 point 8): an explicit OPC UA identifier can write any writable node of",
    "// the server, so the target must be a PLC under test.",
  ];
}

type Placed = { module: MappingModule; channel: IoMappedChannel };

function where({ module, channel }: Placed): string {
  const presentation = presentationOf(module.transport);
  return `${module.key} ${presentation.addressText(channel)}, ${channel.tag}`;
}

// A feedback mapped in two modules shares its variable (ADR 0064 point 5): the
// variable is declared once, whatever its case, and the comment lists every place.
type Variable = { first: Placed; places: string[] };

function variablesOf(placed: readonly Placed[]): Variable[] {
  const byName = new Map<string, Variable>();
  for (const item of placed) {
    const known = byName.get(item.channel.variable.toLowerCase());
    if (known === undefined) {
      byName.set(item.channel.variable.toLowerCase(), { first: item, places: [where(item)] });
    } else {
      known.places.push(where(item));
    }
  }
  return [...byName.values()];
}

function declaration({ first, places }: Variable): string {
  const type = presentationOf(first.module.transport).plcTypeText(first.channel);
  return `  ${first.channel.variable} : ${type}; // ${places.join("; ")}`;
}

function declaredElsewhere({ first, places }: Variable): string {
  const type = presentationOf(first.module.transport).plcTypeText(first.channel);
  return `//   ${first.channel.variable} : ${type} // ${places.join("; ")}`;
}

function externalNote(external: readonly Variable[]): string[] {
  if (external.length === 0) {
    return [];
  }
  return [
    "//",
    "// Declared by your PLC program, not here (a dotted name). Map these channels",
    "// to those variables in the device tree:",
    ...external.map(declaredElsewhere),
  ];
}

/** The text of the GVL for the modules of a valid mapping. */
export function renderGvl(modules: IoMappingResponse["modules"]): string {
  const placed = modules.flatMap((module) =>
    module.channels.map((channel) => ({ module, channel })),
  );
  const generated = placed.filter(({ channel }) => !isDottedVariable(channel.variable));
  const external = placed.filter(({ channel }) => isDottedVariable(channel.variable));
  return [
    ...HEADER,
    ...scopeNote(modules),
    ...externalNote(variablesOf(external)),
    "VAR_GLOBAL",
    ...variablesOf(generated).map(declaration),
    "END_VAR",
    "",
  ].join("\n");
}
