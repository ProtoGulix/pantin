import type { IoMappingResponse } from "@pantin/protocol";
import { describe, expect, it } from "vitest";
import { renderGvl } from "./gvl.ts";

type Module = IoMappingResponse["modules"][number];
type Channel = Module["channels"][number];

function channel(tag: string, variable: string, address: number, ioType: "BOOL" | "REAL"): Channel {
  return {
    tag,
    variable,
    comment: "",
    modbus: { zone: ioType === "BOOL" ? "coil" : "input_register", address, ioType },
    tagType: ioType === "BOOL" ? "bit" : "float",
    direction: "command",
    owner: null,
  };
}

function moduleOf(key: string, channels: Channel[]): Module {
  return {
    key,
    transport: {
      kind: "modbus_tcp_slave",
      port: 1502,
      unitId: 1,
      wordOrder: "low_word_first",
      watchdogMilliseconds: 1000,
    },
    channels,
  };
}

describe("renderGvl", () => {
  it("lists modules in the given order, one commented declaration per channel", () => {
    const text = renderGvl([
      moduleOf("m2", [channel("a.b.c", "a_b_c", 4, "REAL")]),
      moduleOf("m1", [channel("d.e.f", "d_e_f", 0, "BOOL")]),
    ]);
    const lines = text.split("\n");
    const start = lines.indexOf("VAR_GLOBAL");
    expect(lines.slice(start)).toEqual([
      "VAR_GLOBAL",
      "  a_b_c : REAL; // m2 input_register 4, a.b.c",
      "  d_e_f : BOOL; // m1 coil 0, d.e.f",
      "END_VAR",
      "",
    ]);
  });

  it("opens with the generated-file notice and the live outputs warning", () => {
    const text = renderGvl([]);
    expect(text).toMatch(/^\/\/ Generated by "pantin gvl" from io\.json/);
    expect(text).toContain("WARNING (ADR 0046 point 10)");
    expect(text.endsWith("VAR_GLOBAL\nEND_VAR\n")).toBe(true);
  });

  it("leaves a dotted variable out of the declarations and lists it in the header comment", () => {
    const text = renderGvl([
      moduleOf("m1", [
        channel("a.b.c", "GVL_IO.Verin1.FinCourseSortie", 0, "BOOL"),
        channel("d.e.f", "d_e_f", 1, "BOOL"),
      ]),
    ]);
    const [header = "", declarations = ""] = text.split("VAR_GLOBAL\n");
    expect(header).toContain("//   GVL_IO.Verin1.FinCourseSortie : BOOL // m1 coil 0, a.b.c");
    expect(declarations).toBe("  d_e_f : BOOL; // m1 coil 1, d.e.f\nEND_VAR\n");
  });

  it("adds no note to the header when every variable is generated", () => {
    const text = renderGvl([moduleOf("m1", [channel("a.b.c", "a_b_c", 0, "BOOL")])]);
    expect(text).not.toContain("Declared by your PLC program");
  });

  it("declares a variable once when a feedback is mapped in two modules, listing every place", () => {
    const text = renderGvl([
      moduleOf("m1", [channel("a.b.c", "limit", 0, "BOOL"), channel("g.h.i", "GVL.x", 1, "BOOL")]),
      moduleOf("m2", [channel("a.b.c", "LIMIT", 3, "BOOL"), channel("g.h.i", "GVL.x", 4, "BOOL")]),
    ]);
    expect(text.match(/limit : BOOL;/gi)).toHaveLength(1);
    expect(text).toContain("  limit : BOOL; // m1 coil 0, a.b.c; m2 coil 3, a.b.c");
    expect(text.match(/GVL\.x : BOOL/g)).toHaveLength(1);
    expect(text).toContain("//   GVL.x : BOOL // m1 coil 1, g.h.i; m2 coil 4, g.h.i");
  });
});
