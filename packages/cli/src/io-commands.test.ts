import { appendFile, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { IO_LIST_HEADER } from "@pantin/core";
import { IO_FILE_MAX_BYTES } from "@pantin/protocol";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { runCommand } from "./cli.ts";
import { AXIS_TAGS, copyAxisWithValve, tmpWorkspace } from "./io-test-folder.ts";
import { validatePantinFolder } from "./validate-folder.ts";

// pantin io init, pantin gvl and the io part of pantin validate (ADR 0045 point 9).

let workspace: string;
let folder: string;

beforeEach(async () => {
  workspace = await tmpWorkspace();
  folder = await copyAxisWithValve(workspace);
});

afterEach(async () => {
  await rm(workspace, { recursive: true });
});

async function run(args: string[]) {
  const stdout: string[] = [];
  const stderr: string[] = [];
  const code = await runCommand(args, {
    stdout: { write: (text) => stdout.push(text) },
    stderr: { write: (text) => stderr.push(text) },
  });
  return { code, stdout: stdout.join(""), stderr: stderr.join("") };
}

const csvPath = () => join(folder, "io.csv");
const modulesPath = () => join(folder, "io-modules.json");
const csv = () => readFile(csvPath(), "utf8");

const FRESH_CSV = `${IO_LIST_HEADER}
axis.stroke.setpoint;axis_stroke_setpoint;m1;holding_register;0;REAL;
axis.stroke.position;axis_stroke_position;m1;input_register;0;REAL;
axis.valve.coil_14;axis_valve_coil_14;m1;coil;0;BOOL;
axis.valve.coil_12;axis_valve_coil_12;m1;coil;1;BOOL;
`;

const GOLDEN_GVL = `// Generated by "pantin gvl" from io.csv and io-modules.json: do not edit it,
// change the mapping and generate it again.
//
// WARNING (ADR 0046 point 10): a PLC trusts Pantin's feedback. The PLC under
// test must never drive live outputs at the same time: use a SoftPLC, or a
// controller with its field I/O disconnected.
VAR_GLOBAL
  axis_stroke_setpoint : REAL; // m1 holding_register 0, axis.stroke.setpoint
  axis_stroke_position : REAL; // m1 input_register 0, axis.stroke.position
  axis_valve_coil_14 : BOOL; // m1 coil 0, axis.valve.coil_14
  axis_valve_coil_12 : BOOL; // m1 coil 1, axis.valve.coil_12
END_VAR
`;

describe("pantin io init", () => {
  it("writes io.csv in tag list order and io-modules.json with module m1 on port 1502", async () => {
    const result = await run(["io", "init", folder]);
    expect(result).toEqual({ code: 0, stdout: "Wrote io.csv (4 rows).\n", stderr: "" });
    expect(await csv()).toBe(FRESH_CSV);
    expect(JSON.parse(await readFile(modulesPath(), "utf8"))).toEqual({
      schema_version: 1,
      modules: [
        {
          key: "m1",
          port: 1502,
          unitId: 1,
          wordOrder: "low_word_first",
          watchdogMilliseconds: 1000,
        },
      ],
    });
  });

  it("writes files that validate", async () => {
    await run(["io", "init", folder]);
    expect(await validatePantinFolder(folder)).toEqual({ problems: [], notes: [] });
  });

  it("refuses when either file exists, and touches nothing", async () => {
    await writeFile(modulesPath(), "keep me");
    const result = await run(["io", "init", folder]);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("already exists");
    expect(await readFile(modulesPath(), "utf8")).toBe("keep me");
    await rm(modulesPath());
    await writeFile(csvPath(), "keep me too");
    expect((await run(["io", "init", folder])).code).toBe(1);
    expect(await csv()).toBe("keep me too");
  });

  it("refuses a folder that is not a valid Pantin", async () => {
    const result = await run(["io", "init", join(workspace, "nothing")]);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("Is this a Pantin folder?");
  });

  it("takes --update before or after the folder, and refuses other arguments", async () => {
    expect((await run(["io", "init", "--update", folder])).code).toBe(0);
    expect((await run(["io", "init", folder, "--update"])).code).toBe(0);
    expect((await run(["io", "init"])).code).toBe(2);
    expect((await run(["io", "init", folder, "--force"])).code).toBe(2);
    expect((await run(["io", "init", folder, folder])).code).toBe(2);
  });
});

describe("pantin io init --update", () => {
  const USER_ROW = "axis.valve.coil_14;my_valve_extend;m1;coil;5;BOOL;hand written";

  async function writeUserFile(eol: string, finalEol = true): Promise<string> {
    const text = [IO_LIST_HEADER, USER_ROW].join(eol) + (finalEol ? eol : "");
    await writeFile(csvPath(), text);
    await writeFile(
      modulesPath(),
      `${JSON.stringify({ schema_version: 1, modules: [{ key: "m1", port: 1700 }] })}`,
    );
    return text;
  }

  it("appends rows for the unmapped tags only, past the used addresses, keeping the bytes", async () => {
    const before = await writeUserFile("\n");
    const result = await run(["io", "init", folder, "--update"]);
    expect(result).toEqual({ code: 0, stdout: "Appended 3 row(s) to io.csv.\n", stderr: "" });
    expect(await csv()).toBe(
      `${before}axis.stroke.setpoint;axis_stroke_setpoint;m1;holding_register;0;REAL;\n` +
        "axis.stroke.position;axis_stroke_position;m1;input_register;0;REAL;\n" +
        "axis.valve.coil_12;axis_valve_coil_12;m1;coil;6;BOOL;\n",
    );
    expect(await readFile(modulesPath(), "utf8")).toContain('"port":1700');
  });

  it("follows the file's CRLF and adds the missing final line end", async () => {
    const before = await writeUserFile("\r\n", false);
    await run(["io", "init", folder, "--update"]);
    const after = await csv();
    expect(after.startsWith(`${before}\r\naxis.stroke.setpoint;`)).toBe(true);
    expect(after.split("\r\n")).toHaveLength(6);
    expect(after.replaceAll("\r\n", "")).not.toContain("\n");
  });
});

describe("pantin io init --update, files over the size limit", () => {
  it("refuses an io.csv over the limit instead of appending to a truncated read", async () => {
    await run(["io", "init", folder]);
    const big = `${IO_LIST_HEADER}\n${"#".repeat(IO_FILE_MAX_BYTES)}`;
    await writeFile(csvPath(), big);
    const result = await run(["io", "init", folder, "--update"]);
    expect([result.code, result.stderr]).toEqual([
      1,
      expect.stringContaining("too large to update"),
    ]);
    expect(await csv()).toBe(big);
  });

  it("refuses an io-modules.json over the limit", async () => {
    await run(["io", "init", folder]);
    await writeFile(modulesPath(), " ".repeat(IO_FILE_MAX_BYTES + 1));
    const result = await run(["io", "init", folder, "--update"]);
    expect([result.code, result.stderr]).toEqual([1, expect.stringContaining("larger than")]);
  });
});

describe("pantin io init --update, nothing to append or to refuse", () => {
  it("does nothing when every tag is mapped", async () => {
    await run(["io", "init", folder]);
    const before = await csv();
    const result = await run(["io", "init", folder, "--update"]);
    expect(result.stdout).toBe("Nothing to add: every tag is mapped.\n");
    expect(await csv()).toBe(before);
  });

  it("is a plain init when nothing exists, and creates a missing io-modules.json", async () => {
    expect((await run(["io", "init", folder, "--update"])).code).toBe(0);
    expect(await csv()).toBe(FRESH_CSV);
    await rm(modulesPath());
    await appendFile(csvPath(), "");
    expect((await run(["io", "init", folder, "--update"])).code).toBe(0);
    expect(await readFile(modulesPath(), "utf8")).toContain('"port": 1502');
  });

  it("refuses an io.csv with syntax problems, a BOM included, and an io-modules.json without m1", async () => {
    await writeFile(csvPath(), `﻿${IO_LIST_HEADER}\n`);
    const bom = await run(["io", "init", folder, "--update"]);
    expect([bom.code, bom.stderr]).toEqual([1, expect.stringContaining("syntax problems")]);
    await writeFile(csvPath(), `${IO_LIST_HEADER}\n`);
    await writeFile(
      modulesPath(),
      JSON.stringify({ schema_version: 1, modules: [{ key: "m2", port: 1600 }] }),
    );
    const noM1 = await run(["io", "init", folder, "--update"]);
    expect([noM1.code, noM1.stderr]).toEqual([1, expect.stringContaining('no module "m1"')]);
    expect(await csv()).toBe(`${IO_LIST_HEADER}\n`);
  });
});

describe("pantin gvl", () => {
  it("prints the GVL of a valid mapping (golden)", async () => {
    await run(["io", "init", folder]);
    expect(await run(["gvl", folder])).toEqual({ code: 0, stdout: GOLDEN_GVL, stderr: "" });
  });

  it("follows the rows of the file, not the tag list, and notes unmapped tags on stderr", async () => {
    await run(["io", "init", folder]);
    const lines = (await csv()).split("\n");
    await writeFile(csvPath(), [lines[0], lines[3], lines[1], ""].join("\n"));
    const result = await run(["gvl", folder]);
    expect(result.code).toBe(0);
    expect(result.stdout).toContain(
      "axis_valve_coil_14 : BOOL; // m1 coil 0, axis.valve.coil_14\n  axis_stroke_setpoint",
    );
    expect(result.stderr).toBe("note: 2 tag(s) are not mapped and not in the GVL.\n");
  });

  it("refuses an invalid mapping with its problems, and prints no GVL", async () => {
    await run(["io", "init", folder]);
    await writeFile(csvPath(), (await csv()).replace("axis.valve.coil_12", "axis.valve.ghost"));
    const result = await run(["gvl", folder]);
    expect(result.code).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("The mapping is invalid");
    expect(result.stderr).toContain('io.csv:5:1: Tag "axis.valve.ghost" does not exist');
  });

  it("asks for io init when there is no io.csv, and refuses a bad usage", async () => {
    const result = await run(["gvl", folder]);
    expect([result.code, result.stderr]).toEqual([1, expect.stringContaining("pantin io init")]);
    expect((await run(["gvl"])).code).toBe(2);
  });
});

describe("pantin validate and the mapping", () => {
  it("is silent about io when the folder has no io files", async () => {
    expect(await validatePantinFolder(folder)).toEqual({ problems: [], notes: [] });
  });

  it("reports io problems with file, line and column, and fails", async () => {
    await run(["io", "init", folder]);
    await writeFile(csvPath(), (await csv()).replace("m1;coil;1", "m9;coil;1"));
    const unknown = await run(["validate", folder]);
    expect(unknown.code).toBe(1);
    expect(unknown.stderr).toContain('error: io.csv:5:39: Module "m9" is not in io-modules.json.');
    await writeFile(csvPath(), (await csv()).replace("m9;coil;1", "m1;coil;0"));
    expect((await run(["validate", folder])).stderr).toContain("overlaps line 4");
  });

  it("notes unmapped tags without failing", async () => {
    await run(["io", "init", folder]);
    await writeFile(csvPath(), `${(await csv()).split("\n").slice(0, 3).join("\n")}\n`);
    const result = await run(["validate", folder]);
    expect(result.code).toBe(0);
    expect(result.stdout).toContain(
      `2 tag(s) not mapped in io.csv: ${AXIS_TAGS.slice(2).join(", ")}.`,
    );
  });

  it("does not ignore in silence a lone io-modules.json", async () => {
    await writeFile(modulesPath(), "{nope");
    const result = await run(["validate", folder]);
    expect(result.code).toBe(0);
    expect(result.stdout).toContain("io-modules.json exists but there is no io.csv");
    expect(result.stdout).toContain("note: io-modules.json is not valid JSON");
  });

  it("reports a missing io-modules.json beside an io.csv", async () => {
    await run(["io", "init", folder]);
    await rm(modulesPath());
    expect((await run(["validate", folder])).stderr).toContain(
      "io-modules.json: io-modules.json is missing",
    );
  });
});
